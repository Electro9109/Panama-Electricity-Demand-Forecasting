# ============================================================
# Live CND monitoring module for the main Panama Shiny app
# This module is read-only: it does not write to SQLite or
# alter historical data, trained models, or backtest outputs.
# ============================================================

live_monitor_ui <- function(id) {
  ns <- shiny::NS(id)

  shiny::tagList(
    shiny::tags$div(
      class = "live-header",
      shiny::h3("Live Electricity Demand"),
      shiny::p("Current demand and the forecast published by CND / SITR.")
    ),
    shiny::fluidRow(
      shiny::column(4, shiny::tags$div(class = "live-metric-card",
        shiny::tags$div(class = "live-metric-label", "Latest actual demand"),
        shiny::uiOutput(ns("actual_metric")),
        shiny::tags$div(class = "live-metric-unit", "MW")
      )),
      shiny::column(4, shiny::tags$div(class = "live-metric-card",
        shiny::tags$div(class = "live-metric-label", "CND forecast"),
        shiny::uiOutput(ns("forecast_metric")),
        shiny::tags$div(class = "live-metric-unit", "MW")
      )),
      shiny::column(4, shiny::tags$div(class = "live-metric-card",
        shiny::tags$div(class = "live-metric-label", "Actual − forecast"),
        shiny::uiOutput(ns("difference_metric")),
        shiny::tags$div(class = "live-metric-unit", "MW")
      ))
    ),
    shiny::tags$div(class = "live-panel",
      shiny::fluidRow(
        shiny::column(7, shiny::uiOutput(ns("feed_status"))),
        shiny::column(5, shiny::div(style = "text-align:right;",
          shiny::actionButton(ns("refresh_live"), "Refresh live data")
        ))
      ),
      plotly::plotlyOutput(ns("live_plot"), height = "440px")
    ),
    shiny::tags$div(class = "live-panel",
      shiny::h4("Latest readings"),
      shiny::tableOutput(ns("recent_readings"))
    ),
    shiny::tags$div(class = "live-caveat",
      shiny::strong("Interpretation note: "),
      "The CND forecast is provided by the source, not generated by this project's model. ",
      "Its exact lead time is not verified here. This rolling feed is not a permanent archive, ",
      "and the displayed difference is not a formal model evaluation."
    )
  )
}

live_monitor_server <- function(id) {
  shiny::moduleServer(id, function(input, output, session) {
    cnd_url <- "https://sitr.cnd.com.pa/m/pub/data/sin.json"
    panama_tz <- "America/Panama"

    format_live_number <- function(x) {
      if (length(x) == 0L || is.na(x[1]) || !is.finite(as.numeric(x[1]))) return("—")
      format(round(as.numeric(x[1])), big.mark = ",", trim = TRUE, scientific = FALSE)
    }

    get_named_value <- function(x, candidates) {
      if (is.null(x) || is.null(names(x))) return(NULL)
      hit <- intersect(candidates, names(x))
      if (!length(hit)) return(NULL)
      x[[hit[1]]]
    }

    parse_point_time <- function(point) {
      t <- get_named_value(point, c("time", "timestamp", "datetime", "date"))
      if (is.null(t)) return(as.POSIXct(NA, tz = panama_tz))
      if (is.character(t) && length(t) == 1L) {
        return(suppressWarnings(as.POSIXct(t, tz = panama_tz,
          tryFormats = c("%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%OS"))))
      }
      if (is.numeric(t) && length(t) == 1L) {
        return(as.POSIXct(t, origin = "1970-01-01", tz = panama_tz))
      }
      yy <- get_named_value(t, c("y", "year"))
      mm <- get_named_value(t, c("m", "month"))
      dd <- get_named_value(t, c("d", "day"))
      hh <- get_named_value(t, c("h", "hour"))
      mi <- get_named_value(t, c("mi", "minute", "min"))
      ss <- get_named_value(t, c("s", "second", "sec"))
      if (any(vapply(list(yy, mm, dd, hh, mi), is.null, logical(1)))) return(as.POSIXct(NA, tz = panama_tz))
      if (is.null(ss)) ss <- 0
      # The CND JavaScript Date constructor uses zero-based months.
      stamp <- sprintf("%04d-%02d-%02d %02d:%02d:%02d",
        as.integer(yy), as.integer(mm) + 1L, as.integer(dd),
        as.integer(hh), as.integer(mi), as.integer(ss))
      as.POSIXct(stamp, format = "%Y-%m-%d %H:%M:%S", tz = panama_tz)
    }

    extract_values <- function(point) {
      vals <- get_named_value(point, c("values", "value", "data", "y", "val"))
      if (is.null(vals) && is.list(point)) {
        # Some feed versions store series values under an unnamed element.
        possible <- point[!names(point) %in% c("time", "timestamp", "datetime", "date")]
        if (length(possible)) vals <- possible[[1]]
      }
      if (is.null(vals)) stop("CND trend point has no recognised values field.")
      suppressWarnings(as.numeric(unlist(vals, use.names = FALSE)))
    }

    fetch_live <- function() {
      response <- httr::GET(
        cnd_url,
        query = list(cache_bust = as.numeric(Sys.time())),
        httr::add_headers("Cache-Control" = "no-cache, no-store", "Pragma" = "no-cache"),
        httr::timeout(30)
      )
      httr::stop_for_status(response)
      raw_text <- httr::content(response, as = "text", encoding = "UTF-8")
      payload <- jsonlite::fromJSON(raw_text, simplifyVector = FALSE)
      if (is.null(payload$trend$series) || is.null(payload$trend$names)) {
        stop("CND response is missing trend series or labels.")
      }

      labels <- tolower(trimws(unlist(payload$trend$names, use.names = FALSE)))
      actual_i <- match("demanda real", labels)
      forecast_i <- match("demanda pronosticada", labels)
      if (is.na(actual_i) || is.na(forecast_i)) {
        stop("Could not find 'Demanda Real' and 'Demanda Pronosticada' in the CND feed.")
      }

      points <- payload$trend$series
      times <- lapply(points, parse_point_time)
      vals <- lapply(points, extract_values)
      need_i <- max(actual_i, forecast_i)
      if (any(vapply(vals, length, integer(1)) < need_i)) {
        stop("At least one CND trend point has fewer values than its labels.")
      }

      d <- data.frame(
        timestamp = as.POSIXct(unlist(times), origin = "1970-01-01", tz = panama_tz),
        actual = vapply(vals, function(v) v[actual_i], numeric(1)),
        forecast = vapply(vals, function(v) v[forecast_i], numeric(1))
      )
      d <- d[!is.na(d$timestamp) & is.finite(d$actual) & is.finite(d$forecast), , drop = FALSE]
      d <- d[order(d$timestamp), , drop = FALSE]
      rownames(d) <- NULL
      if (nrow(d) < 2L) stop("CND returned fewer than two valid readings.")
      if (anyDuplicated(d$timestamp)) stop("CND returned duplicate timestamps; snapshot rejected.")
      if (any(d$actual < 0) || any(d$forecast < 0)) stop("CND returned negative demand values.")

      list(data = d, source_update = as.character(payload$update %||% "Not provided"), fetched_at = Sys.time())
    }

    # Local null-coalescing helper.
    `%||%` <- function(x, y) if (is.null(x) || length(x) == 0L) y else x

    live_bundle <- shiny::reactive({
      shiny::invalidateLater(60000, session)
      input$refresh_live
      tryCatch(fetch_live(), error = function(e) list(error = conditionMessage(e), fetched_at = Sys.time()))
    })

    output$feed_status <- shiny::renderUI({
      b <- live_bundle()
      if (!is.null(b$error)) {
        return(shiny::tags$div(class = "live-status live-status-error", paste("Feed unavailable:", b$error)))
      }
      shiny::tags$div(class = "live-status live-status-ok", paste0(
        "Connected · ", nrow(b$data), " valid readings · Refreshed ",
        format(b$fetched_at, "%H:%M:%S", tz = panama_tz), " Panama time · Source update: ", b$source_update
      ))
    })

    output$actual_metric <- shiny::renderUI({
      b <- live_bundle(); if (!is.null(b$error)) return(shiny::tags$div(class = "live-metric-value", "—"))
      shiny::tags$div(class = "live-metric-value", format_live_number(tail(b$data$actual, 1)))
    })

    output$forecast_metric <- shiny::renderUI({
      b <- live_bundle(); if (!is.null(b$error)) return(shiny::tags$div(class = "live-metric-value", "—"))
      shiny::tags$div(class = "live-metric-value", format_live_number(tail(b$data$forecast, 1)))
    })

    output$difference_metric <- shiny::renderUI({
      b <- live_bundle(); if (!is.null(b$error)) return(shiny::tags$div(class = "live-metric-value", "—"))
      delta <- tail(b$data$actual - b$data$forecast, 1)
      col <- if (delta > 0) "#B45309" else if (delta < 0) "#2563EB" else "#17324d"
      shiny::tags$div(class = "live-metric-value", style = paste0("color:", col, ";"),
        if (delta > 0) "+" else "", format_live_number(delta))
    })

    output$live_plot <- plotly::renderPlotly({
      b <- live_bundle()
      shiny::validate(shiny::need(is.null(b$error), paste("Unable to load live chart:", b$error)))
      d <- b$data
      plotly::plot_ly(data = d, x = ~timestamp) %>%
        plotly::add_lines(y = ~actual, name = "Actual demand",
          line = list(color = "#2457A7", width = 2),
          hovertemplate = "%{x|%d %b %Y, %H:%M}<br>Actual demand: %{y:,.0f} MW<extra></extra>") %>%
        plotly::add_lines(y = ~forecast, name = "CND forecast",
          line = list(color = "#D97706", width = 2, dash = "dash"),
          hovertemplate = "%{x|%d %b %Y, %H:%M}<br>CND forecast: %{y:,.0f} MW<extra></extra>") %>%
        plotly::layout(
          xaxis = list(title = "", tickformat = "%d %b<br>%H:%M", nticks = 7, automargin = TRUE),
          yaxis = list(title = "Electricity demand (MW)", tickformat = ",.0f", automargin = TRUE, rangemode = "tozero"),
          legend = list(orientation = "v", x = 1.02, y = 1),
          margin = list(l = 65, r = 130, t = 25, b = 65),
          hovermode = "x unified", paper_bgcolor = "white", plot_bgcolor = "white"
        ) %>% plotly::config(displaylogo = FALSE, responsive = TRUE)
    })

    output$recent_readings <- shiny::renderTable({
      b <- live_bundle()
      shiny::validate(shiny::need(is.null(b$error), paste("Unable to load readings:", b$error)))
      d <- head(b$data[order(b$data$timestamp, decreasing = TRUE), , drop = FALSE], 12)
      data.frame(
        `Panama time` = format(d$timestamp, "%d %b %Y, %H:%M", tz = panama_tz),
        `Actual demand (MW)` = vapply(d$actual, format_live_number, character(1)),
        `CND forecast (MW)` = vapply(d$forecast, format_live_number, character(1)),
        `Actual − forecast (MW)` = vapply(d$actual - d$forecast, function(x) paste0(if (x > 0) "+" else "", format_live_number(x)), character(1)),
        check.names = FALSE
      )
    }, striped = TRUE, bordered = FALSE, hover = TRUE, spacing = "s", rownames = FALSE)
  })
}
